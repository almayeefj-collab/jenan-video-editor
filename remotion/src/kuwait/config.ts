export type SceneDef = (typeof scenes)[number];

export const sceneFrames = (s: SceneDef) => VO_LEAD + Math.round(s.dur * FPS) + VO_TAIL;

// إطار نطق كلمة معيّنة داخل المشهد (تقدير بنسبة موقعها في النص)
export const cue = (s: SceneDef, word: string, offset = 0) => {
  const i = s.text.indexOf(word);
  if (i < 0) throw new Error(`cue: «${word}» not in ${s.kind}`);
  return VO_LEAD + Math.round((i / s.text.length) * s.dur * FPS) + offset;
};

// بداية كل مشهد بعد احتساب تداخل الانتقالات
export const timeline = () => {
  let t = 0;
  return scenes.map((s, i) => {
    if (i > 0) t -= TRANSITION;
    const start = t;
    t += sceneFrames(s);
    return {scene: s, start, frames: sceneFrames(s)};
  });
};

export const totalFrames = () => {
  const tl = timeline();
  const last = tl[tl.length - 1];
  return last.start + last.frames;
};
